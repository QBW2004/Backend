param([string]$SdkPath = '', [switch]$Audit)
$ErrorActionPreference = 'Stop'
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../..'))
if (-not $SdkPath) { $SdkPath = Join-Path $repo '.build/mjhl-rtp-native/wasi-sdk-27.0-x86_64-windows' }
$clangPath = Join-Path $SdkPath 'bin/clang.exe'
if (-not (Test-Path -LiteralPath $clangPath)) { throw 'Set -SdkPath to the pinned WASI SDK 27.0 directory. See the task document for the verified download and hash.' }
$out = Join-Path $repo '.build/mjhl-rtp-native'
New-Item -ItemType Directory -Path $out -Force | Out-Null
$wasmPath = Join-Path $out $(if ($Audit) { 'engine-audit.wasm' } else { 'engine.wasm' })
$sourceName = if ($Audit) { 'audit.c' } else { 'engine.c' }
$linker = '-Wl,--no-entry,--export=config_ptr,--export=stats_ptr,--export=configure,--export=reset,--export=sample,--export=sample_spins,--export-memory,--strip-all,--initial-memory=16777216,--max-memory=16777216'
if ($Audit) { $linker += ',--export=audit_grid_ptr,--export=audit_density,--export=audit_probability,--export=audit_symbol_q,--export=audit_conditional_q' }
& $clangPath --target=wasm32-unknown-unknown -O3 -msimd128 -ffp-contract=off -fno-builtin -nostdlib $linker (Join-Path $PSScriptRoot $sourceName) -o $wasmPath
if ($LASTEXITCODE -ne 0) { throw "Compiler failed: $LASTEXITCODE" }
if ($Audit) { Get-FileHash -LiteralPath $wasmPath -Algorithm SHA256; return }
$encoded = [Convert]::ToBase64String([IO.File]::ReadAllBytes($wasmPath))
$script = '/* Generated by Tools/dev/mjhl-rtp-native/build.ps1. Do not edit. */' + "`n" + '(function(root){var data="' + $encoded + '";if(typeof module==="object"&&module.exports)module.exports=data;else root.MjhlRtpWasm=data;})(typeof self!=="undefined"?self:this);' + "`n"
[IO.File]::WriteAllText((Join-Path $repo 'TTY.Web/Scripts/app/mjhl.rtp.wasm.js'),$script,[Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath $wasmPath -Algorithm SHA256
